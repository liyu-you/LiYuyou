def main():
    out = r"C:\Users\LiyuYou\Documents\PureRefBooks\books"
    os.makedirs(out, exist_ok=True)
    written = 0
    for fn, title, author, opening, chapters in BOOKS:
        path = os.path.join(out, fn)
        if os.path.exists(path):
            continue
        parts = [f"{title}\n作者：{author}\n\n", opening, "\n\n=== 目录 ===\n"]
        for i, ch in enumerate(chapters, 1):
            parts.append(f"第{i}回　{ch}\n")
        parts.append("\n\n（本文件为公版经典开篇+目录，完整版可从书库继续补充）\n")
        with open(path, "w", encoding="utf-8") as f:
            f.write("".join(parts))
        written += 1
    print(f"written {written} books to {out}")
    print(f"total files: {len([f for f in os.listdir(out) if f.endswith('.txt')])}")

if __name__ == "__main__":
    main()
